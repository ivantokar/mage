/// Who owns a file, and therefore what Mage may do to it.
public enum FileOwnership: String, Sendable, Codable, CaseIterable {
    /// Written by or for the developer. Mage may create it when it does not exist,
    /// but never replaces or removes it.
    case userOwned

    /// Produced by Mage and regenerated deterministically. Carries an
    /// ``OwnershipMarker``; Mage only replaces or removes files that still have it.
    case mageGenerated

    /// A user-owned file that contains Mage-managed regions (see ``IntegrationHook``).
    /// Mage changes only the content between the region markers.
    case managedIntegration
}

/// The marker that identifies a file as Mage-generated.
///
/// A file is Mage-owned only if its first non-empty line contains this text. Anything
/// else is treated as user-owned, so a developer who takes over a generated file by
/// deleting the header can no longer have it overwritten.
public enum OwnershipMarker {
    public static let text = "Generated by Mage."

    /// The header line to put at the top of a generated file, using the file's comment prefix.
    public static func header(commentPrefix: String = "//") -> String {
        "\(commentPrefix) \(text) Do not edit: changes are overwritten when Mage regenerates this file."
    }

    public static func isMageGenerated(_ contents: String) -> Bool {
        for line in contents.split(separator: "\n", omittingEmptySubsequences: true) {
            return line.contains(text)
        }
        return false
    }
}
