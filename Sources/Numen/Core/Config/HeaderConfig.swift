import Foundation

struct HeaderConfig: Codable {
    let enabled: Bool
    let author: String?
    let email: String?
    let company: String?
    let license: String?

    static let `default` = HeaderConfig(
        enabled: false,
        author: nil,
        email: nil,
        company: nil,
        license: nil
    )

    func generateHeader(fileName: String) -> String {
        guard enabled else { return "" }

        var lines: [String] = ["//"]
        lines.append("//  \(fileName)")

        let authorName = author ?? GitConfig.getUserName()
        let authorEmail = email ?? GitConfig.getUserEmail()

        if let authorName = authorName, !authorName.isEmpty {
            if let authorEmail = authorEmail, !authorEmail.isEmpty {
                lines.append("//  \(authorName) <\(authorEmail)>")
            } else {
                lines.append("//  \(authorName)")
            }
        }

        if let company = company, !company.isEmpty {
            lines.append("//  \(company)")
        }

        let formatter = DateFormatter()
        formatter.dateFormat = "yyyy-MM-dd"
        lines.append("//  \(formatter.string(from: Date()))")
        lines.append("//")
        lines.append("//  Generated by Numen")
        if let license = license, !license.isEmpty {
            lines.append("//  License: \(license)")
        }
        lines.append("//")
        lines.append("")

        return lines.joined(separator: "\n")
    }
}
